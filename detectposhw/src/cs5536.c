/*
 * PIC edge/level configuration registers
 */
#define LXIO(reg, addr) [reg] = { addr, #reg }
const lx_io_t lx_io[LXIO_MAX] = {
	LXIO(PIC_INT_SEL1,	0x4D0),
	LXIO(PIC_INT_SEL2,	0x4D1)
};

/* AMD CS5536 Host Bridge */
#define PCI_VENDOR_AMD		0x1022
#define PCI_DEVICE_CS5536	0x2080

int cs5536(struct pci_dev *pdevs) {
	struct pci_dev *pdev;

	/* Start at Bus 0; Device 1 */
	for (pdev = pdevs; pdev; pdev = pdev->next) {
		if (pdev->vendor_id == PCI_VENDOR_AMD && pdev->device_id == PCI_DEVICE_CS5536)
			return 1;
	}
	return 0;
}
